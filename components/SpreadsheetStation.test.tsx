describe("Ownership, abort and failure boundaries", () => {
  it("a replacement file aborts inspection and an older read cannot restore headers", async () => {
    const tool = withField("file"); let resolve!: (value: SpreadsheetInfo) => void;
    vi.mocked(client.inspectSpreadsheet).mockReturnValueOnce(new Promise(done => { resolve = done; }));
    render(<SpreadsheetStation toolId={tool.id} />); fireEvent.change(byField(tool.id, "file"), { target: { files: [workbook()] } });
    await waitFor(() => expect(client.inspectSpreadsheet).toHaveBeenCalledOnce());
    const signal = vi.mocked(client.inspectSpreadsheet).mock.calls[0][1]!;
    await upload(tool.id); expect(signal.aborted).toBe(true);
    await act(async () => resolve({ sheetNames: ["Obsolete"], sheets: [{ name: "Obsolete", headers: ["Old"], rowCount: 1, columnCount: 1, formulaCount: 0 }] }));
    expect(screen.queryByRole("option", { name: "Obsolete" })).toBeNull(); expect(screen.getByRole("status").textContent).toContain("Local workbook ready");
  });
  it("Clear and unmount abort an in-progress workbook inspection", async () => {
    const tool = withField("file"); vi.mocked(client.inspectSpreadsheet).mockReturnValue(new Promise(() => {}));
    const { unmount } = render(<SpreadsheetStation toolId={tool.id} />);
    fireEvent.change(byField(tool.id, "file"), { target: { files: [workbook()] } }); await waitFor(() => expect(client.inspectSpreadsheet).toHaveBeenCalledOnce());
    fireEvent.click(screen.getByRole("button", { name: "Clear" })); expect(vi.mocked(client.inspectSpreadsheet).mock.calls[0][1]!.aborted).toBe(true);
    fireEvent.change(byField(tool.id, "file"), { target: { files: [workbook()] } }); await waitFor(() => expect(client.inspectSpreadsheet).toHaveBeenCalledTimes(2));
    unmount(); expect(vi.mocked(client.inspectSpreadsheet).mock.calls[1][1]!.aborted).toBe(true);
  });
  it("unmount aborts processing", async () => {
    const tool = withField("file"); vi.mocked(client.runSpreadsheet).mockReturnValueOnce(new Promise(() => {}));
    const { unmount } = render(<SpreadsheetStation toolId={tool.id} />); await fill(tool.id); submit(tool.id); await waitFor(() => expect(client.runSpreadsheet).toHaveBeenCalledOnce());
    const signal = vi.mocked(client.runSpreadsheet).mock.calls[0][2]!; unmount(); expect(signal.aborted).toBe(true);
  });
  it("editing aborts processing and invalidates the old result", async () => {
    const tool = withField("source"); let resolve!: (value: SpreadsheetResult) => void;
    vi.mocked(client.runSpreadsheet).mockReturnValueOnce(new Promise(done => { resolve = done; }));
    const { container } = render(<SpreadsheetStation toolId={tool.id} />); await fill(tool.id); submit(tool.id); await waitFor(() => expect(client.runSpreadsheet).toHaveBeenCalledOnce());
    const signal = vi.mocked(client.runSpreadsheet).mock.calls[0][2]!;
    fireEvent.change(byField(tool.id, "source"), { target: { value: "changed" } }); expect(signal.aborted).toBe(true);
    await act(async () => resolve(mockResult(tool.id))); expect(container.querySelector("table,pre")).toBeNull(); expect(screen.getByRole("status").textContent).toBe("");
  });
  it("inspection failures remain visible, associated and focused", async () => {
    const tool = withField("file"); vi.mocked(client.inspectSpreadsheet).mockRejectedValueOnce(new SpreadsheetError("Encrypted workbooks are unsupported.", "file"));
    render(<SpreadsheetStation toolId={tool.id} />); fireEvent.change(byField(tool.id, "file"), { target: { files: [workbook()] } });
    const alert = await screen.findByRole("alert"); expect(alert.textContent).toContain("Encrypted"); expect(document.activeElement).toBe(byField(tool.id, "file")); expect(screen.queryByRole("combobox")).toBeNull();
  });
  it("generated download URLs are revoked on edits, Clear, unmount and delayed completion", async () => {
    const tool = spreadsheetTools.find(entry => entry.localContract.fields.some(field => field.name === "source"))!;
    vi.spyOn(HTMLAnchorElement.prototype, "click").mockImplementation(() => {});
    const { unmount } = render(<SpreadsheetStation toolId={tool.id} />); await fill(tool.id); submit(tool.id); const download = await screen.findByRole("button", { name: /^Download/ });
    fireEvent.click(download); const first = vi.mocked(URL.createObjectURL).mock.results.at(-1)!.value;
    fireEvent.change(byField(tool.id, "source"), { target: { value: "changed" } }); expect(URL.revokeObjectURL).toHaveBeenCalledWith(first);
    submit(tool.id); fireEvent.click(await screen.findByRole("button", { name: /^Download/ })); const second = vi.mocked(URL.createObjectURL).mock.results.at(-1)!.value;
    fireEvent.click(screen.getByRole("button", { name: "Clear" })); expect(URL.revokeObjectURL).toHaveBeenCalledWith(second);
    await fill(tool.id); submit(tool.id); fireEvent.click(await screen.findByRole("button", { name: /^Download/ })); const third = vi.mocked(URL.createObjectURL).mock.results.at(-1)!.value;
    unmount(); expect(URL.revokeObjectURL).toHaveBeenCalledWith(third);
    render(<SpreadsheetStation toolId={tool.id} />); await fill(tool.id); submit(tool.id); fireEvent.click(await screen.findByRole("button", { name: /^Download/ })); const fourth = vi.mocked(URL.createObjectURL).mock.results.at(-1)!.value;
    await waitFor(() => expect(URL.revokeObjectURL).toHaveBeenCalledWith(fourth), { timeout: 1800 });
  });
  it("copy failure keeps selectable text; stale clipboard completion cannot restore notice", async () => {
    const tool = spreadsheetTools.find(entry => /^excel-to-(?:csv|tsv|json|markdown|html)$/.test(entry.id))!;
    const user = userEvent.setup(); let resolve!: () => void;
    const copy = vi.spyOn(navigator.clipboard, "writeText").mockRejectedValueOnce(new Error("denied")).mockImplementationOnce(() => new Promise(done => { resolve = done; }));
    render(<SpreadsheetStation toolId={tool.id} />); await fill(tool.id); submit(tool.id); await user.click(await screen.findByRole("button", { name: /^Copy/ }));
    expect(screen.getByRole("status").textContent).toContain("Could not copy"); expect(screen.getByLabelText("Generated text").getAttribute("tabindex")).toBe("0");
    await user.click(screen.getByRole("button", { name: /^Copy/ })); await user.click(screen.getByRole("button", { name: "Clear" })); await act(async () => resolve()); expect(screen.getByRole("status").textContent).toBe(""); expect(copy).toHaveBeenCalledTimes(2);
  });
});
