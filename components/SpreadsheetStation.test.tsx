import * as client from "@/lib/tools/spreadsheet/client";
import SpreadsheetStation from "./SpreadsheetStation";

vi.mock("@/lib/tools/spreadsheet/client", () => ({ inspectSpreadsheet: vi.fn(), runSpreadsheet: vi.fn() }));
const info: SpreadsheetInfo = { sheetNames: ["First", "Second"], sheets: [
  { name: "First", headers: ["Name", "Name", ""], rowCount: 3, columnCount: 3, formulaCount: 0 },
  { name: "Second", headers: ["Amount", "Total"], rowCount: 2, columnCount: 2, formulaCount: 1 },
] };
const workbook = () => new File(["local workbook"], "private-local.xlsx", { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" });
const definition = (id: SpreadsheetToolId) => spreadsheetTools.find(tool => tool.id === id)!;
const byField = (id: SpreadsheetToolId, name: string) => screen.getByLabelText(definition(id).localContract.fields.find(field => field.name === name)!.label);
const submit = (id: SpreadsheetToolId) => fireEvent.click(screen.getByRole("button", { name: definition(id).localContract.action }));
const withField = (name: string) => spreadsheetTools.find(tool => tool.localContract.fields.some(field => field.name === name))!;
const viewer = () => spreadsheetTools.find(tool => tool.id.endsWith("viewer"))!;
function mockResult(id: SpreadsheetToolId, sheet = "First"): SpreadsheetResult {
  const tool = definition(id);
  const textual = /^excel-to-(?:csv|tsv|json|markdown|html)$/.test(id);
  const inspecting = /viewer|inspector|analyzer/.test(id);
  return {
    ...(textual ? { text: "<script>private cell</script>\nα,β" } : {}),
    ...(!inspecting ? { files: [{ name: textual ? "converted.txt" : "converted.xlsx", blob: new Blob(["full generated bytes"]) }, ...(id.includes("splitter") && !id.includes("column") ? [{ name: "second.xlsx", blob: new Blob(["second bytes"]) }] : [])] } : {}),
    data: { rows: 2, columns: 3 },
    preview: { sheetNames: info.sheetNames, name: sheet, rows: [["Name", "Name", ""], ["<img src='https://example.com/x'>", "α", "=not executed"]] },
  };
}
async function upload(id: SpreadsheetToolId) {
  fireEvent.change(byField(id, "file"), { target: { files: [workbook()] } });
  await waitFor(() => expect(screen.getByRole("status").textContent).toContain("Local workbook ready"));
}
async function fill(id: SpreadsheetToolId) {
  const contract = definition(id).localContract;
  if (contract.fields.some(field => field.name === "file")) await upload(id);
  if (contract.fields.some(field => field.name === "files")) fireEvent.change(byField(id, "files"), { target: { files: [workbook(), new File(["second"], "second.xlsx")] } });
  for (const field of contract.fields) {
    if (["file", "files", "textFile", "sheet", "order", "keys"].includes(field.name)) continue;
    const control = byField(id, field.name);
    if (field.name === "column") fireEvent.change(control, { target: { value: "1" } });
    else if (field.control !== "select") fireEvent.change(control, { target: { value: field.name === "sheetName" ? "Output" : field.name === "source" ? id.includes("json") ? '[{"name":"local"}]' : "name,value\nlocal,1" : "local" } });
  }
}
beforeEach(() => {
  let sequence = 0;
  Object.defineProperty(URL, "createObjectURL", { configurable: true, value: vi.fn(() => `blob:local-${++sequence}`) });
  Object.defineProperty(URL, "revokeObjectURL", { configurable: true, value: vi.fn() });
  vi.mocked(client.inspectSpreadsheet).mockResolvedValue(info);
  vi.mocked(client.runSpreadsheet).mockImplementation(async (id, values) => mockResult(id as SpreadsheetToolId, typeof values.sheet === "string" && values.sheet ? values.sheet : "First"));
});
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.clearAllMocks(); vi.unstubAllGlobals(); document.documentElement.removeAttribute("data-theme"); });

describe.each(["light", "dark"])("Spreadsheet %s theme DOM (not visual acceptance)", theme => {
  it.each(spreadsheetTools)("$id exact action, keyboard, outputs, copy/download, Clear and privacy", async tool => {
    document.documentElement.dataset.theme = theme;
    const user = userEvent.setup();
    const clipboard = vi.spyOn(navigator.clipboard, "writeText").mockResolvedValue();
    const anchor = vi.spyOn(HTMLAnchorElement.prototype, "click").mockImplementation(() => {});
    const fetch = vi.fn(); vi.stubGlobal("fetch", fetch);
    const xhr = vi.spyOn(XMLHttpRequest.prototype, "send");
    const storage = vi.spyOn(Storage.prototype, "setItem");
    const beacon = vi.fn(); Object.defineProperty(navigator, "sendBeacon", { configurable: true, value: beacon });
    const log = vi.spyOn(console, "log");
    const { container } = render(<SpreadsheetStation toolId={tool.id} />);
    expect(container.querySelector('[name="sheet"]')).toBeNull();
    await fill(tool.id);
    expect(client.runSpreadsheet).not.toHaveBeenCalled();
    for (const field of tool.localContract.fields) {
      const control = ["keys", "order"].includes(field.name) ? container.querySelector(`[data-spreadsheet-field="${field.name}"]`) : byField(tool.id, field.name);
      expect(control?.id).toBe(`spreadsheet-${tool.id}-${field.name}`);
    }
    const action = screen.getByRole("button", { name: tool.localContract.action }); action.focus(); await user.keyboard("{Enter}");
    await waitFor(() => expect(screen.getByRole("status").textContent).toBe("Result ready."));
    expect(client.runSpreadsheet).toHaveBeenCalledOnce();
    expect(screen.getByRole("heading", { name: tool.localContract.outputs.join(" · ") })).toBeTruthy();
    const actual = await vi.mocked(client.runSpreadsheet).mock.results[0].value as SpreadsheetResult;
    if (actual.text !== undefined) { const copy = screen.getByRole("button", { name: /^Copy/ }); copy.focus(); await user.keyboard("{Enter}"); expect(clipboard).toHaveBeenLastCalledWith(actual.text); }
    else { expect(screen.queryByRole("button", { name: /^Copy/ })).toBeNull(); expect(clipboard).not.toHaveBeenCalled(); }
    expect(screen.queryAllByRole("button", { name: /^Download/ })).toHaveLength(actual.files?.length ?? 0);
    for (const file of actual.files ?? []) {
      const button = screen.getByRole("button", { name: `Download ${file.name}` }); button.focus(); await user.keyboard("{Enter}");
      expect(vi.mocked(URL.createObjectURL).mock.calls.at(-1)?.[0]).toBe(file.blob);
      const link = anchor.mock.instances.at(-1) as unknown as HTMLAnchorElement; expect(link.download).toBe(file.name); expect(document.body.contains(link)).toBe(false);
    }
    expect(container.querySelector("script,img,iframe")).toBeNull();
    expect(screen.getByText("<img src='https://example.com/x'>")).toBeTruthy();
    const clear = screen.getByRole("button", { name: "Clear" }); clear.focus(); await user.keyboard("{Enter}");
    expect(container.querySelector("table,pre")).toBeNull(); expect(screen.queryByRole("alert")).toBeNull(); expect(screen.getByRole("status").textContent).toBe("");
    for (const input of container.querySelectorAll<HTMLInputElement>('input[type="file"]')) expect(input.value).toBe("");
    expect(fetch).not.toHaveBeenCalled(); expect(xhr).not.toHaveBeenCalled(); expect(storage).not.toHaveBeenCalled(); expect(beacon).not.toHaveBeenCalled(); expect(log).not.toHaveBeenCalled();
  });
});

describe("All spreadsheet contracts", () => {
  it("contains exactly 20 public contracts", () => expect(spreadsheetTools).toHaveLength(20));
  it.each(spreadsheetTools)("$id empty input is associated and focused without running", async tool => {
    render(<SpreadsheetStation toolId={tool.id} />); submit(tool.id);
    const alert = await screen.findByRole("alert"); expect(alert.textContent).toMatch(/required|Choose/);
    const first = byField(tool.id, tool.localContract.fields.find(field => ["file", "files", "source"].includes(field.name))!.name);
    expect(document.activeElement).toBe(first); expect(first.getAttribute("aria-describedby")).toContain(alert.id); expect(first.getAttribute("aria-invalid")).toBe("true");
    expect(client.runSpreadsheet).not.toHaveBeenCalled();
  });
  it.each(spreadsheetTools)("$id invalid processing shows an inert useful error", async tool => {
    const first = tool.localContract.fields[0];
    vi.mocked(client.runSpreadsheet).mockRejectedValueOnce(new SpreadsheetError("Malformed input: <script> stays text", first.name));
    const { container } = render(<SpreadsheetStation toolId={tool.id} />); await fill(tool.id); submit(tool.id);
    expect((await screen.findByRole("alert")).textContent).toBe("Malformed input: <script> stays text");
    expect(container.querySelector("script")).toBeNull(); expect(document.activeElement).toBe(byField(tool.id, first.name));
    fireEvent.click(screen.getByRole("button", { name: "Clear" })); expect(screen.queryByRole("alert")).toBeNull();
  });
  it.each(spreadsheetTools)("$id Clear aborts work and rejects stale completion", async tool => {
    let resolve!: (value: SpreadsheetResult) => void;
    vi.mocked(client.runSpreadsheet).mockReturnValueOnce(new Promise(done => { resolve = done; }));
    const { container } = render(<SpreadsheetStation toolId={tool.id} />); await fill(tool.id); submit(tool.id);
    await waitFor(() => expect(client.runSpreadsheet).toHaveBeenCalledOnce());
    const signal = vi.mocked(client.runSpreadsheet).mock.calls[0][2]!;
    fireEvent.click(screen.getByRole("button", { name: "Clear" })); expect(signal.aborted).toBe(true);
    await act(async () => resolve(mockResult(tool.id)));
    expect(container.querySelector("table,pre")).toBeNull(); expect(screen.getByRole("status").textContent).toBe("");
  });
  it.each(spreadsheetTools)("$id SSR hydration has stable field IDs and no recovery errors", async tool => {
    const element = <SpreadsheetStation toolId={tool.id} />;
    const container = document.createElement("div"); container.innerHTML = renderToString(element); document.body.appendChild(container);
    const ids = [...container.querySelectorAll("[id]")].map(node => node.id);
    const recover = vi.fn(); let root!: ReturnType<typeof hydrateRoot>;
    await act(async () => { root = hydrateRoot(container, element, { onRecoverableError: recover }); });
    expect([...container.querySelectorAll("[id]")].map(node => node.id)).toEqual(ids); expect(recover).not.toHaveBeenCalled();
    expect(client.inspectSpreadsheet).not.toHaveBeenCalled(); expect(client.runSpreadsheet).not.toHaveBeenCalled();
    await act(async () => root.unmount()); container.remove();
  });
});

