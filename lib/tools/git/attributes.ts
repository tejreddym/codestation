import { assertGitInput } from "./limits";

export type GitAttributesEol = "auto" | "lf" | "crlf" | "preserve";
export type GitLinguistFlag = "none" | "generated" | "vendored" | "documentation";

export interface GitAttributesInput {
  eol: GitAttributesEol;
  binaryGlobs?: string;
  linguistGlobs?: string;
  linguistFlag?: GitLinguistFlag;
  exportIgnore?: string;
}

export interface GitAttributesResult {
  content: string;
  ruleCount: number;
}

const MAX_PATTERNS = 200;
const MAX_PATTERN_LENGTH = 200;

function parseGlobs(value: string | undefined): string[] {
  if (!value) return [];
  const patterns = value
    .split(/[\n,]+/)
    .map((pattern) => pattern.trim())
    .filter(Boolean);

  if (patterns.length > MAX_PATTERNS) {
    throw new Error(`Use at most ${MAX_PATTERNS} patterns per group.`);
  }

  return patterns.map((pattern) => {
    if (pattern.length > MAX_PATTERN_LENGTH) {
      throw new Error(`Pattern "${pattern.slice(0, 24)}…" exceeds ${MAX_PATTERN_LENGTH} characters.`);
    }
    if (/\s/.test(pattern) || pattern.includes('"')) {
      throw new Error(`Pattern "${pattern}" is invalid: Git attribute patterns cannot contain whitespace or quotes.`);
    }
    return pattern;
  });
}

const EOL_RULES: Record<GitAttributesEol, string> = {
  auto: "* text=auto",
  lf: "* text=auto eol=lf",
  crlf: "* text=auto eol=crlf",
  preserve: "* -text",
};

const LINGUIST_RULES: Record<Exclude<GitLinguistFlag, "none">, string> = {
  generated: "linguist-generated=true",
  vendored: "linguist-vendored=true",
  documentation: "linguist-documentation=true",
};

/** Generate deterministic `.gitattributes` content from explicit policies. */
export function generateGitAttributes(input: GitAttributesInput): GitAttributesResult {
  assertGitInput(input.binaryGlobs ?? "", "Binary globs");
  assertGitInput(input.linguistGlobs ?? "", "Linguist globs");
  assertGitInput(input.exportIgnore ?? "", "Export-ignore patterns");

  const eol = input.eol ?? "auto";
  if (!(eol in EOL_RULES)) throw new Error("Choose a valid line-ending policy.");

  const linguistFlag = input.linguistFlag ?? "none";
  if (!(linguistFlag === "none" || linguistFlag in LINGUIST_RULES)) {
    throw new Error("Choose a valid linguist flag.");
  }

  const binaryGlobs = parseGlobs(input.binaryGlobs);
  const linguistGlobs = parseGlobs(input.linguistGlobs);
  const exportIgnore = parseGlobs(input.exportIgnore);

  if (linguistFlag !== "none" && !linguistGlobs.length) {
    throw new Error("Add at least one path glob for the selected linguist flag.");
  }

  const lines: string[] = [
    "# .gitattributes generated by Code Station.",
    "# Review these rules before committing them to your repository.",
    "",
    "# Line endings",
    EOL_RULES[eol],
  ];

  if (binaryGlobs.length) {
    lines.push("", "# Binary files (no text normalization or diffs)");
    for (const glob of binaryGlobs) lines.push(`${glob} binary`);
  }

  if (linguistFlag !== "none" && linguistGlobs.length) {
    lines.push("", `# GitHub linguist: ${linguistFlag}`);
    for (const glob of linguistGlobs) lines.push(`${glob} ${LINGUIST_RULES[linguistFlag]}`);
  }

  if (exportIgnore.length) {
    lines.push("", "# Exclude from git archive exports");
    for (const glob of exportIgnore) lines.push(`${glob} export-ignore`);
  }

  const unique = [...new Set(lines)];
  const ruleCount = unique.filter((line) => line && !line.startsWith("#")).length;
  return { content: `${unique.join("\n")}\n`, ruleCount };
}
