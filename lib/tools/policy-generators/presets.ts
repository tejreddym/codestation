/**
 * Retrieve the configuration options for a specific policy tool and preset vertical.
 * Defaults to the "saas" preset if the specified preset name is not recognized.
 */
export function getPolicyPreset(
  toolId: PolicyToolId,
  presetName: string
): Record<string, unknown> {
  const normName = (presetName || "").toLowerCase().trim() as PresetVertical;
  const preset = POLICY_PRESETS[normName] || POLICY_PRESETS.saas;

  switch (toolId) {
    case "privacy-policy-generator":
      return { ...preset.privacyPolicy };
    case "terms-and-conditions-generator":
      return { ...preset.termsAndConditions };
    case "cookie-policy-generator":
      return { ...preset.cookiePolicy };
    case "disclaimer-generator":
      return { ...preset.disclaimer };
    case "refund-policy-generator":
      return { ...preset.refundPolicy };
    default:
      return {};
  }
}

/**
 * List all available policy presets with descriptions.
 */
export function listPolicyPresets(
  _toolId?: PolicyToolId
): Array<{ id: string; name: string; description: string }> {
  return Object.values(POLICY_PRESETS).map((p) => ({
    id: p.id,
    name: p.name,
    description: p.description,
  }));
}
